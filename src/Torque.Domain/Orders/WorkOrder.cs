using Torque.Domain.Common;

namespace Torque.Domain.Orders;

public enum WorkOrderStatus
{
    Open,
    InProgress,
    Completed,
    Closed,
    Cancelled,
}

public enum DiscountType
{
    Percent,
    Amount,
}

public enum LineKind
{
    Service,
    Part,
}

/// <summary>Discount above the limit needs an Admin. The API turns it into HTTP 403.</summary>
public sealed class DiscountApprovalRequiredException(string message) : DomainException(message);

/// <summary>
/// A work order ("заказ-наряд"): what was done to the car and how much it costs.
/// It is the aggregate root for its lines: lines are added and removed only through it, so the totals
/// can never disagree with the lines. Payments are separate append-only records, but the paid amount
/// is tracked here so the "never overpay" rule can be checked in one place.
/// </summary>
public sealed class WorkOrder : Entity, IHasTimestamps
{
    /// <summary>Managers may give up to 15% off; more needs the owner (Admin).</summary>
    public const decimal MaxDiscountPercentWithoutApproval = 15m;

    private readonly List<WorkOrderLine> _lines = [];

    private WorkOrder() { }

    /// <summary>Human-friendly sequential number (WO-1042), generated by the database.</summary>
    public long Number { get; private set; }
    public Guid? AppointmentId { get; private set; }
    public Guid CustomerId { get; private set; }
    public Guid VehicleId { get; private set; }
    public Guid? MechanicId { get; private set; }
    public WorkOrderStatus Status { get; private set; }
    public DiscountType? DiscountType { get; private set; }
    public decimal? DiscountValue { get; private set; }
    public decimal Subtotal { get; private set; }
    public decimal DiscountAmount { get; private set; }
    public decimal Total { get; private set; }
    public decimal PaidAmount { get; private set; }
    public DateTimeOffset? CompletedAt { get; private set; }
    public DateTimeOffset? ClosedAt { get; private set; }
    public IReadOnlyCollection<WorkOrderLine> Lines => _lines;
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }

    public decimal AmountDue => Total - PaidAmount;

    public static WorkOrder Open(Guid customerId, Guid vehicleId, Guid? appointmentId) => new()
    {
        CustomerId = customerId,
        VehicleId = vehicleId,
        AppointmentId = appointmentId,
        Status = WorkOrderStatus.Open,
    };

    // ---- lines -------------------------------------------------------------------------------

    /// <summary>The catalog name and price are copied: changing the price list later never changes this order.</summary>
    public WorkOrderLine AddService(Guid serviceId, string name, decimal unitPrice, decimal quantity) =>
        AddLine(WorkOrderLine.Create(Id, LineKind.Service, serviceId, name, quantity, unitPrice));

    public WorkOrderLine AddPart(string name, decimal unitPrice, decimal quantity) =>
        AddLine(WorkOrderLine.Create(Id, LineKind.Part, null, name, quantity, unitPrice));

    public void RemoveLine(Guid lineId)
    {
        EnsureEditable();
        var line = _lines.SingleOrDefault(l => l.Id == lineId)
            ?? throw new DomainException($"Line '{lineId}' is not part of this work order.");
        var totals = Calculate(_lines.Where(l => l != line), DiscountType, DiscountValue);
        _lines.Remove(line);
        Apply(totals);
    }

    // ---- discount ----------------------------------------------------------------------------

    public void ApplyDiscount(DiscountType type, decimal value, bool approvedByAdmin)
    {
        EnsureEditable();
        if (value < 0 || (type == Orders.DiscountType.Percent && value > 100))
        {
            throw new DomainException("Discount must be between 0 and 100% (or a non-negative amount).");
        }

        DiscountType? newType = value == 0 ? null : type;
        decimal? newValue = value == 0 ? null : value;
        var totals = Calculate(_lines, newType, newValue);

        if (!approvedByAdmin && totals.Subtotal > 0
            && totals.DiscountAmount / totals.Subtotal * 100 > MaxDiscountPercentWithoutApproval)
        {
            throw new DiscountApprovalRequiredException(
                $"A discount above {MaxDiscountPercentWithoutApproval}% must be given by an Admin.");
        }

        DiscountType = newType;
        DiscountValue = newValue;
        Apply(totals);
    }

    // ---- lifecycle ---------------------------------------------------------------------------

    public void Start(Guid mechanicId)
    {
        if (Status != WorkOrderStatus.Open)
        {
            throw new InvalidStateException($"Cannot start a work order that is {Status}.");
        }

        MechanicId = mechanicId;
        Status = WorkOrderStatus.InProgress;
    }

    public void Complete(DateTimeOffset now)
    {
        if (Status != WorkOrderStatus.InProgress)
        {
            throw new InvalidStateException($"Cannot complete a work order that is {Status}.");
        }

        if (_lines.Count == 0)
        {
            throw new DomainException("Cannot complete a work order without any lines.");
        }

        Status = WorkOrderStatus.Completed;
        CompletedAt = now;
        CloseIfPaid(now);
    }

    public void Cancel()
    {
        if (Status is not (WorkOrderStatus.Open or WorkOrderStatus.InProgress))
        {
            throw new InvalidStateException($"Cannot cancel a work order that is {Status}.");
        }

        if (PaidAmount != 0)
        {
            throw new DomainException("Refund the payments before cancelling the work order.");
        }

        Status = WorkOrderStatus.Cancelled;
    }

    // ---- money -------------------------------------------------------------------------------

    /// <summary>
    /// Records money received. Prepayment is allowed while work is in progress; overpayment never is.
    /// Callers must hold a lock on this order row (see PaymentService) so two cashiers cannot both
    /// pass the "amount ≤ due" check at the same time.
    /// </summary>
    public void RegisterPayment(decimal amount, DateTimeOffset now)
    {
        if (Status is WorkOrderStatus.Cancelled or WorkOrderStatus.Closed)
        {
            throw new InvalidStateException($"Cannot take a payment for a work order that is {Status}.");
        }

        if (!Money.IsValidAmount(amount))
        {
            throw new DomainException("Payment amount must be positive with at most 2 decimal places.");
        }

        if (amount > AmountDue)
        {
            throw new DomainException($"Payment {amount:0.00} exceeds the amount due {AmountDue:0.00}.");
        }

        PaidAmount += amount;
        CloseIfPaid(now);
    }

    public void RegisterRefund(decimal amount)
    {
        if (!Money.IsValidAmount(amount))
        {
            throw new DomainException("Refund amount must be positive with at most 2 decimal places.");
        }

        if (amount > PaidAmount)
        {
            throw new DomainException($"Refund {amount:0.00} exceeds the paid amount {PaidAmount:0.00}.");
        }

        PaidAmount -= amount;
        if (Status == WorkOrderStatus.Closed)
        {
            Status = WorkOrderStatus.Completed;
            ClosedAt = null;
        }
    }

    private WorkOrderLine AddLine(WorkOrderLine line)
    {
        EnsureEditable();
        var totals = Calculate(_lines.Append(line), DiscountType, DiscountValue);
        _lines.Add(line);
        Apply(totals);
        return line;
    }

    private void EnsureEditable()
    {
        if (Status is not (WorkOrderStatus.Open or WorkOrderStatus.InProgress))
        {
            throw new InvalidStateException($"A work order that is {Status} cannot be changed.");
        }
    }

    private readonly record struct Totals(decimal Subtotal, decimal DiscountAmount, decimal Total);

    /// <summary>
    /// Pure calculation of the totals for a prospective state. Every change first computes and validates,
    /// and only then mutates — so a rejected change leaves the order exactly as it was.
    /// </summary>
    private Totals Calculate(IEnumerable<WorkOrderLine> lines, DiscountType? type, decimal? value)
    {
        var subtotal = lines.Sum(l => l.LineTotal);
        var discount = type switch
        {
            Orders.DiscountType.Percent => Money.Round(subtotal * value!.Value / 100m),
            Orders.DiscountType.Amount => Math.Min(value!.Value, subtotal),
            _ => 0m,
        };
        var total = subtotal - discount;

        if (total < PaidAmount)
        {
            throw new DomainException("The new total would be less than what the customer has already paid.");
        }

        return new Totals(subtotal, discount, total);
    }

    private void Apply(Totals totals) => (Subtotal, DiscountAmount, Total) = (totals.Subtotal, totals.DiscountAmount, totals.Total);

    private void CloseIfPaid(DateTimeOffset now)
    {
        if (Status == WorkOrderStatus.Completed && AmountDue == 0)
        {
            Status = WorkOrderStatus.Closed;
            ClosedAt = now;
        }
    }
}

public sealed class WorkOrderLine : Entity
{
    public const int MaxNameLength = 200;

    private WorkOrderLine() { }

    public Guid WorkOrderId { get; private set; }
    public LineKind Kind { get; private set; }
    public Guid? ServiceId { get; private set; }

    /// <summary>Snapshot of the name at the time of sale.</summary>
    public string Name { get; private set; } = null!;
    public decimal Quantity { get; private set; }

    /// <summary>Snapshot of the price at the time of sale.</summary>
    public decimal UnitPrice { get; private set; }
    public decimal LineTotal { get; private set; }

    internal static WorkOrderLine Create(Guid workOrderId, LineKind kind, Guid? serviceId, string name, decimal quantity, decimal unitPrice)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            throw new DomainException("Line name is required.");
        }

        if (quantity <= 0 || decimal.Round(quantity, 2) != quantity || quantity > 1000)
        {
            throw new DomainException("Quantity must be positive, at most 1000, with at most 2 decimal places.");
        }

        if (unitPrice < 0 || decimal.Round(unitPrice, 2) != unitPrice)
        {
            throw new DomainException("Unit price must be non-negative with at most 2 decimal places.");
        }

        return new WorkOrderLine
        {
            WorkOrderId = workOrderId,
            Kind = kind,
            ServiceId = serviceId,
            Name = name.Trim(),
            Quantity = quantity,
            UnitPrice = unitPrice,
            LineTotal = Money.Round(quantity * unitPrice),
        };
    }
}
