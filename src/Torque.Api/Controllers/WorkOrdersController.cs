using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Torque.Api.Setup;
using Torque.Application.Common;
using Torque.Application.Orders;
using Torque.Domain.Orders;

namespace Torque.Api.Controllers;

/// <summary>
/// Work orders and their payments. Mechanics work on their own orders; front desk manages everything.
/// </summary>
[ApiController]
[Route("api/v1/work-orders")]
[Produces("application/json")]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status401Unauthorized)]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status403Forbidden)]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound)]
public sealed class WorkOrdersController(WorkOrderService orders, PaymentService payments) : ControllerBase
{
    private const string IdempotencyHeader = "Idempotency-Key";

    /// <summary>Open from a checked-in appointment (pre-filled with its services) or as a walk-in.</summary>
    [HttpPost]
    [Authorize(Policy = Policies.FrontDesk)]
    [ProducesResponseType<WorkOrderDto>(StatusCodes.Status201Created)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity)]
    public async Task<ActionResult<WorkOrderDto>> Open(OpenWorkOrderRequest request, CancellationToken ct)
    {
        var order = await orders.OpenAsync(request, ct);
        return CreatedAtAction(nameof(Get), new { id = order.Id }, order);
    }

    /// <summary>List (mechanics see only their own and unassigned orders).</summary>
    [HttpGet]
    public Task<PagedResult<WorkOrderSummaryDto>> List(
        [FromQuery] WorkOrderStatus? status,
        [FromQuery] Guid? customerId,
        [FromQuery] Guid? mechanicId,
        [FromQuery] int page = 1,
        [FromQuery] int pageSize = 20,
        CancellationToken ct = default) =>
        orders.ListAsync(new WorkOrderListQuery(new PageRequest(page, pageSize), status, customerId, mechanicId), ct);

    [HttpGet("{id:guid}")]
    public Task<WorkOrderDto> Get(Guid id, CancellationToken ct) => orders.GetAsync(id, ct);

    /// <summary>Add a catalog service. Name and price are copied (snapshot).</summary>
    [HttpPost("{id:guid}/lines/services")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> AddService(Guid id, AddServiceLineRequest request, CancellationToken ct) =>
        orders.AddServiceAsync(id, request, ct);

    /// <summary>Add a part or consumable with a free-text name and price.</summary>
    [HttpPost("{id:guid}/lines/parts")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> AddPart(Guid id, AddPartLineRequest request, CancellationToken ct) =>
        orders.AddPartAsync(id, request, ct);

    [HttpDelete("{id:guid}/lines/{lineId:guid}")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> RemoveLine(Guid id, Guid lineId, CancellationToken ct) => orders.RemoveLineAsync(id, lineId, ct);

    /// <summary>Discount; above 15% only an Admin (403 otherwise).</summary>
    [HttpPut("{id:guid}/discount")]
    [Authorize(Policy = Policies.FrontDesk)]
    public Task<WorkOrderDto> Discount(Guid id, DiscountRequest request, CancellationToken ct) =>
        orders.ApplyDiscountAsync(id, request, ct);

    /// <summary>Start work. A mechanic assigns themselves; front desk passes mechanicId.</summary>
    [HttpPost("{id:guid}/start")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> Start(Guid id, StartWorkRequest request, CancellationToken ct) => orders.StartAsync(id, request, ct);

    [HttpPost("{id:guid}/complete")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> Complete(Guid id, CancellationToken ct) => orders.CompleteAsync(id, ct);

    [HttpPost("{id:guid}/cancel")]
    [Authorize(Policy = Policies.FrontDesk)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict)]
    public Task<WorkOrderDto> Cancel(Guid id, CancellationToken ct) => orders.CancelAsync(id, ct);

    /// <summary>
    /// Take a payment. Requires header <c>Idempotency-Key</c> (e.g. a UUID generated by the client once per
    /// payment attempt). Repeating the request with the same key returns 200 with the original payment
    /// instead of charging twice; a new payment returns 201.
    /// </summary>
    [HttpPost("{id:guid}/payments")]
    [Authorize(Policy = Policies.FrontDesk)]
    [ProducesResponseType<PaymentResult>(StatusCodes.Status201Created)]
    [ProducesResponseType<PaymentResult>(StatusCodes.Status200OK)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity)]
    public async Task<ActionResult<PaymentResult>> Pay(
        Guid id, PaymentRequest request, [FromHeader(Name = IdempotencyHeader)] string? idempotencyKey, CancellationToken ct) =>
        Respond(await payments.PayAsync(id, request, idempotencyKey, ct));

    /// <summary>Refund (Admin only), same idempotency rules.</summary>
    [HttpPost("{id:guid}/refunds")]
    [Authorize(Policy = Policies.AdminOnly)]
    [ProducesResponseType<PaymentResult>(StatusCodes.Status201Created)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity)]
    public async Task<ActionResult<PaymentResult>> Refund(
        Guid id, PaymentRequest request, [FromHeader(Name = IdempotencyHeader)] string? idempotencyKey, CancellationToken ct) =>
        Respond(await payments.RefundAsync(id, request, idempotencyKey, ct));

    private ActionResult<PaymentResult> Respond(PaymentResult result) =>
        result.Replayed ? Ok(result) : StatusCode(StatusCodes.Status201Created, result);
}
