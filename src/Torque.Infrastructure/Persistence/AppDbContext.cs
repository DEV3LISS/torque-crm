using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;
using Torque.Application.Abstractions;
using Torque.Domain.Auditing;
using Torque.Domain.Auth;
using Torque.Domain.Catalog;
using Torque.Domain.Common;
using Torque.Domain.Customers;
using Torque.Domain.Messaging;
using Torque.Domain.Orders;
using Torque.Domain.Scheduling;
using Torque.Domain.Users;

namespace Torque.Infrastructure.Persistence;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options), IAppDbContext
{
    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Vehicle> Vehicles => Set<Vehicle>();
    public DbSet<ServiceOffering> Services => Set<ServiceOffering>();
    public DbSet<Bay> Bays => Set<Bay>();
    public DbSet<WorkingHours> WorkingHours => Set<WorkingHours>();
    public DbSet<Appointment> Appointments => Set<Appointment>();
    public DbSet<WorkOrder> WorkOrders => Set<WorkOrder>();
    public DbSet<Payment> Payments => Set<Payment>();
    public DbSet<AuditLog> AuditLogs => Set<AuditLog>();
    public DbSet<OutboxMessage> OutboxMessages => Set<OutboxMessage>();

    public Task<IDbContextTransaction> BeginTransactionAsync(CancellationToken cancellationToken = default) =>
        Database.BeginTransactionAsync(cancellationToken);

    public async Task<WorkOrder?> LockWorkOrderAsync(Guid id, CancellationToken cancellationToken = default)
    {
        // FromSql is parameterised: {id} becomes @p0, never string concatenation → no SQL injection.
        // FOR UPDATE: other transactions that try to lock or update this row wait until we commit.
        var order = await WorkOrders
            // "SELECT *" does not include the system column xmin, which EF reads as the concurrency token.
            .FromSql($"SELECT *, xmin FROM work_orders WHERE id = {id} FOR UPDATE")
            .SingleOrDefaultAsync(cancellationToken);

        if (order is not null)
        {
            await Entry(order).Collection(o => o.Lines).LoadAsync(cancellationToken);
        }

        return order;
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Picks up every IEntityTypeConfiguration<T> in this assembly (Configurations/ folder),
        // so each table's mapping lives in its own small file.
        modelBuilder.HasPostgresExtension("btree_gist"); // lets a GiST index combine "=" on uuid with "&&" on ranges
        modelBuilder.HasPostgresExtension("pg_trgm");    // trigram index for fast "name contains …" search
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Ids are UUIDv7 generated by the application (Entity base class), never by the database.
        // Telling EF this matters: otherwise a NEW child added to a tracked aggregate (e.g. a work order line)
        // already has a non-empty key, EF assumes it exists, issues UPDATE instead of INSERT, updates 0 rows
        // and reports a false concurrency conflict.
        foreach (var entity in modelBuilder.Model.GetEntityTypes().Where(e => typeof(Entity).IsAssignableFrom(e.ClrType)))
        {
            modelBuilder.Entity(entity.ClrType).Property(nameof(Entity.Id)).ValueGeneratedNever();
        }
    }

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        // All enums are stored as readable text ('Admin', not 0). Reordering enum members can then
        // never silently change the meaning of existing rows.
        configurationBuilder.Properties<Enum>().HaveConversion<string>().HaveMaxLength(32);
    }
}
